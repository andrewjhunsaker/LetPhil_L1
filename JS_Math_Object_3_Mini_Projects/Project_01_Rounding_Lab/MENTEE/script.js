/* STEP 1 — Create a decimal number */
// Create a number called value (example: 7.6)
// console.log it
// ✅ WRITE YOUR CODE UNDER THIS LINE
const value = 7.6;
console.log("Value:", value);

/* STEP 2 — Math.round() */
// Use Math.round(value)
// console.log the result
// ✅ WRITE YOUR CODE UNDER THIS LINE
const rounded = Math.round(value);
console.log("Rounded:", rounded);

/* STEP 3 — Math.floor() */
// Use Math.floor(value)
// console.log the result
// ✅ WRITE YOUR CODE UNDER THIS LINE
const roundedDown = Math.floor(value);
console.log("Rounded down:", roundedDown);

/* STEP 4 — Math.ceil() */
// Use Math.ceil(value)
// console.log the result
// ✅ WRITE YOUR CODE UNDER THIS LINE
const roundedUp = Math.ceil(value);
console.log("Rounded up:", roundedUp);
